def _e(id, name, cat, diff, kind, sets, amount, rest, how, skill="", anim=""):
    return dict(id=id, name=name, category=cat, difficulty=diff, kind=kind, default_sets=sets,
                default_amount=amount, default_rest=rest, instructions=how, skill_id=skill or None,
                anim=anim)


