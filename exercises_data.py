"""Built-in exercise library. Synced into the `exercises` table on startup.

_e(id, name, category, difficulty 0-3, kind 'reps'|'hold', default sets,
   default reps or hold seconds, default rest seconds, instructions, skill_id, anim)

`skill_id` links an exercise to the skill tree: finishing a workout can update
that skill's personal record.
`anim` is the key of the movement animation in `animations.py` (empty = no animation).
"""
