"""Static skill-tree data.

Each skill is a node; `prereqs` are the edges. Layout is computed automatically
(see graph.py), so to extend the tree just add a `_s(...)` line.

_s(id, name, category, tier, prereqs, description, steps, exercises,
   regressions, unit, target, note)

* prereqs      : space-separated skill ids
* steps        : progression steps, separated by "|"
* exercises    : recommended training (sets / reps / holds), separated by "|"
* regressions  : easier variations, separated by "|"
* unit/target  : benchmark used for personal records (e.g. "reps", 10)
"""
from dataclasses import dataclass

CATEGORIES = {
    "push": ("Pushing", "#ff6b6b"),
    "pull": ("Pulling", "#4dabf7"),
    "core": ("Core", "#ffd43b"),
    "balance": ("Balance", "#b197fc"),
    "static": ("Static Holds", "#38d9a9"),
    "legs": ("Legs", "#ff922b"),
}
TIERS = ["Beginner", "Intermediate", "Advanced", "Elite"]
TIER_XP = [10, 25, 60, 150]


@dataclass(frozen=True)
class Skill:
    id: str
    name: str
    category: str
    tier: int
    prereqs: tuple
    description: str
    steps: tuple
    exercises: tuple
    regressions: tuple
    unit: str = ""
    target: float = 0
    note: str = ""


def _s(id, name, cat, tier, pre, desc, steps, rx, reg="", unit="", target=0, note=""):
    return Skill(
        id, name, cat, tier,
        tuple(pre.split()), desc,
        tuple(steps.split("|")), tuple(rx.split("|")),
        tuple(x for x in reg.split("|") if x),
        unit, target, note,
    )


